"""Сшивает master_profile.md + supplement_profile.md в один компактный profile_compact.md.

Цель: 25-35K вместо 226K без потери критичной информации.
Запуск разовый: python3 consolidate_profile.py
"""
import os
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).parent
load_dotenv(ROOT / ".env", override=True)

from llm import Anthropic  # noqa: E402

client = Anthropic(api_key=os.environ.get("ANTHROPIC_API_KEY", ""))


CONSOLIDATE_PROMPT = """ты редактор-психолог. сшиваешь два документа о ване в ОДИН компактный профиль для AI-психолога.

цель: получить плотный markdown 25-35K символов, который даёт AI-психологу всё нужное для точной работы. без воды.

структура итогового документа:

# Ваня · профиль клиента

## 1. Базовое
возраст, локация, чем зарабатывает, ключевые роли, семья. 5-10 строк.

## 2. Психопортрет
тип личности, центральные защиты, перфекционизм, самооценка, attachment style, ранние схемы (по Янгу), темперамент. плотно, без шаблонов. 30-50 строк.

## 3. Эмоциональные паттерны
триггеры, реакции на стресс, типичные искажения (catastrophizing, mind reading, etc.), регуляция, что делает в spirale down. 20-30 строк.

## 4. Ценности и драйверы
что важно НА САМОМ ДЕЛЕ (не декларации). страхи, источники самоуважения. 10-15 строк.

## 5. Цели и проекты
текущая стадия жизни, активные проекты, цели на 1-3-5 лет если упомянуты. 10-15 строк.

## 6. Отношения
ключевые фигуры (родители, партнёры, ключевые друзья). паттерны в отношениях. 10-15 строк.

## 7. Стиль и речь
как разговаривает (примеры маркеров стиля). что любит/не любит из эстетики (кино, музыка). чтобы AI-психолог говорил на одной волне. 15-20 строк.

## 8. Здоровье
физическое состояние, сон, нагрузки, употребление, генетика если есть данные. 10-15 строк.

## 9. История
ключевые жизненные события, переломы, инсайты из дневника за 2023-2026 (если есть). 15-25 строк.

## 10. Что работает / не работает
какие интервенции у вани заходят, какие отскакивают. метафоры из киноязыка ему ложатся. 10-15 строк.

ПРАВИЛА:
— строчные буквы, плотный текст, без воды
— конкретика, цифры, имена, цитаты — везде где есть в источниках
— противоречия источников разрешай в пользу более свежего/специфичного
— ничего не выдумывай — только из источников
— не используй markdown bold (**), не используй заголовки глубже ###
— дубликаты схлопывай, не повторяй одно и то же в разных секциях

выдавай ТОЛЬКО итоговый markdown, без преамбул и комментариев."""


def main() -> None:
    master = (ROOT / "master_profile.md").read_text()
    supplement_path = ROOT / "supplement_profile.md"
    supplement = supplement_path.read_text() if supplement_path.exists() else ""
    raw = (
        f"=== ДОКУМЕНТ 1: master_profile ===\n\n{master}\n\n"
        f"=== ДОКУМЕНТ 2: supplement_profile ===\n\n{supplement}"
    )
    print(f"вход: {len(raw):,} chars")
    # qwen3-next 256K context справится с такими объёмами
    resp = client.messages.create(
        model="qwen/qwen3-next-80b-a3b-instruct:free",
        max_tokens=12000,
        system=CONSOLIDATE_PROMPT,
        messages=[{"role": "user", "content": raw}],
    )
    compact = resp.content[0].text.strip()
    out = ROOT / "profile_compact.md"
    out.write_text(compact)
    print(f"выход: {len(compact):,} chars → {out}")


if __name__ == "__main__":
    main()
